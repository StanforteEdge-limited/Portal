function extraBlockedDomains(): Set<string> {
  const raw = process.env.EXTRA_BLOCKED_EMAIL_DOMAINS || '';
  return new Set(
    raw
      .split(',')
      .map((d) => d.trim().toLowerCase())
      .filter(Boolean),
  );
}

/**
 * Returns true if the given email belongs to a known disposable/temporary email
 * domain or any subdomain thereof (e.g. `x.mailinator.com`).
 */
export function isDisposableEmail(email: string): boolean {
  const normalized = String(email || '').trim().toLowerCase();
  const atIndex = normalized.lastIndexOf('@');
  if (atIndex === -1 || atIndex === normalized.length - 1) return false;
  const domain = normalized.slice(atIndex + 1).replace(/\.+$/, '');
  if (!domain) return false;

  const extra = extraBlockedDomains();
  const labels = domain.split('.');
  for (let i = 0; i < labels.length - 1; i += 1) {
    const candidate = labels.slice(i).join('.');
    if (DISPOSABLE_EMAIL_DOMAINS.has(candidate) || extra.has(candidate)) {
      return true;
    }
  }
  return false;
}

/**
 * Throws a 400 BadRequestException if the email uses a disposable/temporary provider.
 */
export function assertNonDisposableEmail(email: string): void {
  if (isDisposableEmail(email)) {
    throw new BadRequestException(
      'Disposable or temporary email addresses are not allowed. Please use a valid work or personal email address.',
    );
  }
}
